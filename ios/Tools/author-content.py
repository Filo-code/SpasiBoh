def side(text, pron=None, stressed=None, audio=None, rank=9999, example=None):
    return {
        "text": text,
        "stressed": stressed,
        "pronunciation": pron,
        "audioText": audio or text,
        "frequencyRank": rank,
        "example": example,
    }


def note(it, ru):
    return {"it": it, "ru": ru}


# ---------------------------------------------------------------- patterns
# The Russian-speaking learner already reads Latin script. The real difficulty
# is Italian orthography: digraphs that do not exist in Russian, consonant
# length that carries meaning, and stress that is not marked in writing.
# `pronunciation` is written for a Russian ear, which is what this field is for.

def pattern(id, kind, pat, pron, key, word, translated, confusable=None,
            minimal=None, note_=None, order=0):
    return {
        "id": id, "kind": kind, "pattern": pat, "pronunciation": pron,
        "soundKey": key, "exampleWord": word, "exampleWordTranslated": translated,
        "confusableWith": confusable or [], "minimalPair": minimal,
        "note": note_, "order": order,
    }


def pair(short, short_it, short_ru, long, long_it, long_ru):
    return {
        "short": short, "shortMeaning": note(short_it, short_ru),
        "long": long, "longMeaning": note(long_it, long_ru),
    }


